CREATE TABLE IF NOT EXISTS accounts (id TEXT PRIMARY KEY, created INTEGER NOT NULL, updated INTEGER NOT NULL, blob TEXT);
CREATE TABLE IF NOT EXISTS creds (id TEXT PRIMARY KEY, uid TEXT NOT NULL, pk TEXT NOT NULL, counter INTEGER NOT NULL DEFAULT 0, transports TEXT, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS creds_uid ON creds(uid);
CREATE TABLE IF NOT EXISTS sessions (h TEXT PRIMARY KEY, uid TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_uid ON sessions(uid);
CREATE TABLE IF NOT EXISTS chal (c TEXT PRIMARY KEY, kind TEXT NOT NULL, uid TEXT, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rl (k TEXT PRIMARY KEY, n INTEGER NOT NULL, exp INTEGER NOT NULL);
